#!/usr/bin/env bash
# tests/server-diag.sh: S0b (docs/parallel.md C4, C5). One long-lived probe
# `serve` process elaborates one module through a sequence of changes. After
# each change, the runner asserts that the probe's messages equal the output
# of `lake env lean --json` on the same text: the same JSON objects (severity,
# range, message text, kind), in the same order.
#
# Part 1, tests/fixtures/server-diag/Diag.lean: five changes in sequence:
# an edit that removes an error, an edit that adds an error, an edit in the
# first declaration, an edit in the last declaration, and a revert to the
# first text.
# Part 2, Big.lean, which this runner generates: one module of $big_n
# theorems, and one edit near its end. The runner measures the full-file
# `lake env lean --json` time and the probe's time for the change.
#
# stdout: the tests/lib/report.sh object. Its "measures.*" keys hold the wall
# time of each change, the full-file time and the peak resident size of each
# probe process.
set -euo pipefail
source "$(dirname "$0")/lib/report.sh"
root="$(cd "$(dirname "$0")/.." && pwd)"
work="$root/.scratch/server-diag"
fail=0
big_n=200

rm -rf "$work"
mkdir -p "$work/versions"
cp -r "$root/tests/fixtures/server-diag/." "$work/"
cat "$root/lean-toolchain" > "$work/lean-toolchain"
cp "$root/probe/Probe.lean" "$work/Probe.lean"

ms() { echo $(($(date +%s%N) / 1000000)); }

# The versions of Diag.lean. Each change edits the text before it; the revert
# copies the first text back.
v="$work/versions"
cp "$work/Diag.lean" "$v/diag-0.lean"
change() {  # change <from> <to> <sed expression>
  sed "$3" "$v/$1.lean" >"$v/$2.lean"
  if cmp -s "$v/$1.lean" "$v/$2.lean"; then
    echo "the change $2 did not change the text"
    exit 1
  fi
}
change diag-0 remove-error 's/exact unknownLemma n/exact Nat.le_succ n/'
change remove-error add-error 's/^  omega$/  exact unknownMid/'
change add-error edit-first 's/^def double (n : Nat)/def double (n m : Nat)/'
change edit-first edit-last 's/n + 0 = n := by simp$/n + 0 = n := by exact unknownLast/'
cp "$v/diag-0.lean" "$v/revert.lean"
diag_changes=(remove-error add-error edit-first edit-last revert)

# Big.lean: $big_n theorems, each elaborated by `simp` and `omega`. The edit
# breaks the proof of theorem number $big_n - 5.
{
  echo "/-! Generated by tests/server-diag.sh: $big_n theorems. -/"
  for i in $(seq 1 "$big_n"); do
    echo ""
    echo "theorem big_$i (xs ys zs : List Nat) (a b : Nat) (h : a < b) :"
    echo "    ((xs ++ ys ++ zs ++ [a, $i]).map (· + $i)).reverse.length ="
    echo "      zs.length + ys.length + xs.length + 2 ∧ a + $i < b + $i ∧"
    echo "    (xs.filter (· > $i) ++ ys).length ≤ xs.length + ys.length := by"
    echo "  refine ⟨?_, ?_, ?_⟩"
    echo "  · simp; omega"
    echo "  · omega"
    echo "  · simp [List.length_append]; exact List.length_filter_le _ _"
  done
} >"$v/big-0.lean"
edit_at=$((big_n - 5))
awk -v t="theorem big_$edit_at " '
  index($0, t) == 1 { inside = 1 }
  inside && $0 == "  · omega" { print "  · exact unknownNearEnd"; inside = 0; next }
  { print }' "$v/big-0.lean" >"$v/big-edit.lean"
cmp -s "$v/big-0.lean" "$v/big-edit.lean" && { echo "the Big.lean edit did not change the text"; exit 1; }

# The expected messages: `lake env lean --json` on each version, computed
# before any probe process starts. A `lake env` call inherits each open pipe
# fd of this shell, and one left open makes that call wait for ever (see
# tests/probe-serve.sh), so no one-shot call runs while a request fifo is open.
lean_json() {  # lean_json <file in $work>: its messages as one JSON array
  (cd "$work" && lake env lean --json "$1" || true) | jq -s -c '.'
}
declare -A want
for c in diag-0 "${diag_changes[@]}"; do
  cp "$v/$c.lean" "$work/Diag.lean"
  want[$c]=$(lean_json Diag.lean)
done
for c in big-0 big-edit; do
  cp "$v/$c.lean" "$work/Big.lean"
  start=$(ms)
  want[$c]=$(lean_json Big.lean)
  full_ms=$(($(ms) - start))
  measure "big.$c.lean_json_wall_ms" "$full_ms"
done
measure big.declarations "$big_n"

# One probe `serve` process, its request and reply fifos on fds 7 and 8.
serve_start() {
  rm -f "$work/req.fifo" "$work/rep.fifo"
  mkfifo "$work/req.fifo" "$work/rep.fifo"
  (cd "$work" && exec lake env lean --run Probe.lean serve <"$work/req.fifo" >"$work/rep.fifo") &
  probe_pid=$!
  exec 7>"$work/req.fifo" 8<"$work/rep.fifo"
}
# serve_stop <measure prefix>: the peak resident size of the `lean` child of
# the `lake` wrapper, which holds the elaborated state; then end of file on
# stdin, which ends the `serve` loop.
serve_stop() {
  local lean_pid="" p pid ppid
  for p in /proc/[0-9]*; do
    pid=${p#/proc/}
    ppid=$(awk '{print $4}' "$p/stat" 2>/dev/null) || continue
    if [ "$ppid" = "$probe_pid" ]; then lean_pid=$pid; break; fi
  done
  measure "$1.peak_rss_kb" "$(awk '/VmHWM/ {print $2}' "/proc/${lean_pid:-$probe_pid}/status")"
  exec 7>&-
  wait "$probe_pid"
  exec 8<&-
}
# elaborate <version> <module file> <check name>: put the version in place,
# send one `elaborate` request, and compare the reply with `lake env lean
# --json` on the same text. Sets $elab_ms to the request's wall time.
elaborate() {
  local reply got start
  cp "$v/$1.lean" "$work/$2"
  start=$(ms)
  jq -nc --arg f "$2" '{op: "elaborate", file: $f}' >&7
  read -r reply <&8
  elab_ms=$(($(ms) - start))
  got=$(jq -c '.messages' <<<"$reply")
  if [ "$got" = "${want[$1]}" ]; then pass "$3"; else
    failed "$3"
    echo "probe:          $got"
    echo "lean --json:    ${want[$1]}"
  fi
}

serve_start
elaborate diag-0 Diag.lean "Diag.lean opened: messages equal lake env lean --json"
measure diag.open.wall_ms "$elab_ms"
for c in "${diag_changes[@]}"; do
  elaborate "$c" Diag.lean "Diag.lean change $c: messages equal lake env lean --json"
  measure "diag.$c.wall_ms" "$elab_ms"
done
serve_stop diag

serve_start
elaborate big-0 Big.lean "Big.lean opened: messages equal lake env lean --json"
measure big.open.wall_ms "$elab_ms"
elaborate big-edit Big.lean "Big.lean edit near the end: messages equal lake env lean --json"
measure big.edit.wall_ms "$elab_ms"
# C4: the probe elaborates again only from the edited theorem near the end,
# so the change costs a small part of the full-file `lake env lean --json`
# time on the same text ($full_ms, from the loop above).
if [ $((elab_ms * 4)) -lt "$full_ms" ]; then
  pass "the Big.lean edit takes less than a quarter of the full-file time"
else failed "the Big.lean edit takes less than a quarter of the full-file time"; fi
serve_stop big

# Each change must change the messages, or an equal reply would not show that
# the probe saw the change.
distinct=$(for c in diag-0 "${diag_changes[@]}"; do echo "${want[$c]}"; done | sort -u | wc -l)
# The revert gives the first text again, so 5 distinct message lists of 6.
if [ "$distinct" -eq 5 ]; then pass "every Diag.lean change changes the messages"
else failed "every Diag.lean change changes the messages"; fi
if [ "${want[big-0]}" != "${want[big-edit]}" ]; then pass "the Big.lean edit changes the messages"
else failed "the Big.lean edit changes the messages"; fi
report
